import type { BilingualText, Language } from '../types/cms';

export function getLocalizedText(
  value: BilingualText | string | null | undefined,
  lang: Language
): string {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  const primary = value[lang]?.trim();
  if (primary) return primary;
  const fallback = lang === 'ar' ? value.en?.trim() : value.ar?.trim();
  return fallback || '';
}

export function isTranslationMissing(
  value: BilingualText | null | undefined,
  lang: Language
): boolean {
  if (!value) return false;
  return !value[lang] || value[lang].trim().length === 0;
}

